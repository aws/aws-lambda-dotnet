#!/usr/bin/env python3
"""Generate template.yaml for the OpenTelemetry conformance handlers.

Every case is deployed once per view (otel-invocation, otel-execution), and the runner needs the
requirement id as a literal in TestingMetadata, so the template is 2x the case list. Edit CASES and
rerun this script instead of editing template.yaml by hand:

    python3 scripts/generate_template.py > template.yaml
"""

from __future__ import annotations

# (case number, scenario class, extra properties). "target" adds a chained-invoke target function
# whose scenario class is the value; "timeout" overrides the execution timeout in seconds.
CASES = [
    (1, "Otel1Success", {}),
    (2, "Otel2WaitResume", {}),
    (3, "Otel3Retry", {}),
    (4, "Otel4TerminalFailure", {}),
    (5, "Otel5ChildContext", {}),
    (6, "Otel6Parallel", {}),
    (7, "Otel7Map", {}),
    (8, "Otel8HandledFailure", {}),
    (9, "Otel9WaitForCondition", {}),
    (10, "Otel10WaitForCallback", {}),
    (11, "Otel11ChainedInvoke", {"target": "Otel11InvokeTarget"}),
    (12, "Otel12ChildContextFailure", {}),
    (13, "Otel13ParallelFailure", {}),
    (14, "Otel14MapFailure", {}),
    (15, "Otel15WaitInterrupted", {"timeout": 15}),
    (16, "Otel16WaitForConditionFailure", {}),
    (17, "Otel17WaitForCallbackFailure", {}),
    (18, "Otel18ChainedInvokeFailure", {"target": "Otel18InvokeTarget"}),
    (19, "Otel19ExecutionFailure", {}),
    (20, "Otel20VirtualContext", {}),
    (21, "Otel21CompletedStepReplay", {}),
    (22, "Otel22UserFunctionContext", {}),
    (25, "Otel25CaughtCallbackFailureReplay", {}),
    (26, "Otel26ExternalCompletionReplay", {}),
    (27, "Otel27ChainedInvokeSuspend", {"target": "Otel27InvokeTarget"}),
]

# Requirements the .NET SDK cannot express, reported NOT_IMPLEMENTED (non-blocking). Declared on case 1's function.
NOT_IMPLEMENTED = {
    23: "Needs a with-retry helper for durable child contexts; the .NET SDK has none.",
    24: "Needs a public way for a workflow to request an invocation retry; in .NET a workflow exception fails the execution.",
}

VIEWS = (
    ("otel-invocation", "Invocation", "invocation"),
    ("otel-execution", "Execution", "execution"),
)

HEADER = """\
AWSTemplateFormatVersion: "2010-09-09"
Transform: AWS::Serverless-2016-10-31
Description: .NET SDK examples for the durable execution OTel conformance suites. Generated by scripts/generate_template.py.

Parameters:
  LambdaExecutionRoleArn:
    Type: String
    Description: Pre-created execution role for the test functions
  OtelSuite:
    Type: String
    Default: all
    AllowedValues:
      - all
      - otel-invocation
      - otel-execution
    Description: OpenTelemetry view whose functions should be deployed
  OtelLayerArn:
    Type: String
    Description: Collector Lambda layer that receives the spans over OTLP (ADOT collector layer for X-Ray)
  OtelCollectorLayerArn:
    Type: String
    Default: ""
    Description: Optional OpenTelemetry Collector Lambda extension layer
  OtelCollectorBucket:
    Type: String
    Default: ""
    Description: S3 bucket where the collector writes OTLP trace objects
  OtelCollectorPrefix:
    Type: String
    Default: ""
    Description: S3 key prefix where the collector writes OTLP trace objects
  OtelExecWrapper:
    Type: String
    Default: ""
    Description: Lambda execution wrapper. Empty for .NET, which has no auto-instrumentation layer
  OtelServiceName:
    Type: String
    Default: durable-execution-conformance
    Description: OpenTelemetry resource service name
  OtelTracesExporter:
    Type: String
    Default: otlp
    Description: OpenTelemetry traces exporter selected by the runner
  OtelExporterEndpoint:
    Type: String
    Default: ""
    Description: Non-secret OTLP endpoint. Empty sends to the collector layer on localhost
  OtelExporterHeaders:
    Type: String
    Default: ""
    NoEcho: true
    Description: Secret OTLP exporter headers supplied by the runner
  OtelSecretEnvironmentNames:
    Type: String
    Default: ""
    Description: Comma-separated secret environment variable names

Conditions:
  HasOtelCollectorLayer: !Not [!Equals [!Ref OtelCollectorLayerArn, ""]]
  HasOtelExecWrapper: !Not [!Equals [!Ref OtelExecWrapper, ""]]
  HasOtelExporterEndpoint: !Not [!Equals [!Ref OtelExporterEndpoint, ""]]
  HasOtelExporterHeaders: !Not [!Equals [!Ref OtelExporterHeaders, ""]]
  DeployInvocationView: !Or
    - !Equals [!Ref OtelSuite, all]
    - !Equals [!Ref OtelSuite, otel-invocation]
  DeployExecutionView: !Or
    - !Equals [!Ref OtelSuite, all]
    - !Equals [!Ref OtelSuite, otel-execution]

# The same bootstrap serves every function. CONFORMANCE_SCENARIO selects the case and OTEL_PLUGIN_MODE the view.
# publish/Makefile (written by scripts/build_examples.sh) copies the one published bundle into each artifact.
Globals:
  Function:
    Runtime: dotnet10
    Architectures:
      - x86_64
    Timeout: 60
    MemorySize: 512
    Tracing: Active
    Layers: !If
      - HasOtelCollectorLayer
      - [!Ref OtelLayerArn, !Ref OtelCollectorLayerArn]
      - [!Ref OtelLayerArn]
    DurableConfig:
      ExecutionTimeout: 300
      RetentionPeriodInDays: 1
    Environment:
      Variables:
        AWS_LAMBDA_EXEC_WRAPPER: !If [HasOtelExecWrapper, !Ref OtelExecWrapper, !Ref "AWS::NoValue"]
        OTEL_SERVICE_NAME: !Ref OtelServiceName
        OTEL_TRACES_EXPORTER: !Ref OtelTracesExporter
        OTEL_EXPORTER_OTLP_ENDPOINT: !If [HasOtelExporterEndpoint, !Ref OtelExporterEndpoint, "http://localhost:4318"]
        OTEL_EXPORTER_OTLP_HEADERS: !If [HasOtelExporterHeaders, !Ref OtelExporterHeaders, !Ref "AWS::NoValue"]
        OTEL_EXPORTER_OTLP_PROTOCOL: http/protobuf
        OTEL_PROPAGATORS: xray
        OTEL_TRACES_SAMPLER: always_on
        OTEL_S3_BUCKET: !Ref OtelCollectorBucket
        OTEL_S3_PREFIX: !Ref OtelCollectorPrefix
        OPENTELEMETRY_COLLECTOR_CONFIG_URI: !If
          - HasOtelCollectorLayer
          - /opt/collector-config/config-s3.yaml
          - /var/task/collector-xray.yaml

Resources:
"""


def function(logical_id, condition, name, scenario, mode, extra, requirement=None):
    """One function. requirement is the TestingMetadata id; targets of chained invokes have none."""
    lines = [f"  {logical_id}:", "    Type: AWS::Serverless::Function", f"    Condition: {condition}",
             "    Metadata:", "      BuildMethod: makefile"]
    if requirement:
        lines += ["    TestingMetadata:", "      TestDescription:", f"        - {requirement}"]
        if requirement.endswith("-1"):
            view_id = requirement[: -len("-1")]
            lines.append("      NotImplemented:")
            for case, reason in NOT_IMPLEMENTED.items():
                lines += [f"        - id: {view_id}-{case}", f"          reason: {reason}"]
    lines += ["    Properties:", "      CodeUri: publish/", "      Handler: bootstrap",
              f'      FunctionName: !Sub "${{AWS::StackName}}-{name}"',
              "      Role: !Ref LambdaExecutionRoleArn"]
    if "timeout" in extra:
        lines += ["      DurableConfig:", f"        ExecutionTimeout: {extra['timeout']}", "        RetentionPeriodInDays: 1"]
    lines += ["      Environment:", "        Variables:",
              f"          CONFORMANCE_SCENARIO: {scenario}",
              f"          OTEL_PLUGIN_MODE: {mode}"]
    if "target_id" in extra:
        lines.append(f'          OTEL_INVOKE_TARGET_FUNCTION_NAME: !Sub "${{{extra["target_id"]}.Arn}}:$LATEST"')
    return "\n".join(lines) + "\n"


def main() -> None:
    out = [HEADER]
    for view_id, view_label, mode in VIEWS:
        condition = f"Deploy{view_label}View"
        for case, scenario, extra in CASES:
            extra = dict(extra)
            target = extra.pop("target", None)
            if target:
                extra["target_id"] = f"{view_label}{target}"
            out.append(function(f"{view_label}{scenario}", condition, f"{view_id}-{case}", scenario, mode, extra,
                                requirement=f"{view_id}-{case}"))
            if target:
                out.append(function(f"{view_label}{target}", condition, f"{view_id}-{case}-target", target, mode, {}))
    print("\n".join(out), end="")


if __name__ == "__main__":
    main()
